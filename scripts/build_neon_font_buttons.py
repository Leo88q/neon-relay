def sheet_icon_none() -> Canvas:
    c = Canvas(128, 128)
    c.vgradient(0, 0, 128, 128, [(0, (16, 22, 40, 255)), (1, (8, 10, 22, 255))])
    c.circle(64, 64, 40, (77, 227, 247, 255), fill=False, width=7)
    c.line(36, 92, 92, 36, (255, 46, 136, 255), 7)
    return c


def sheet_icon_auto() -> Canvas:
    c = Canvas(128, 64)
    # day half / night half
    c.vgradient(0, 0, 64, 64, [(0, (255, 214, 140, 255)), (1, (255, 150, 80, 255))])
    c.vgradient(64, 0, 128, 64, [(0, (10, 16, 38, 255)), (1, (24, 34, 70, 255))])
    c.circle(32, 30, 12, (255, 246, 220, 255))
    for sx, sy in ((80, 16), (96, 30), (110, 14), (88, 44), (106, 48)):
        c.set(sx, sy, (216, 238, 252, 255))
        c.set(sx + 1, sy, (216, 238, 252, 160))
    c.circle(100, 34, 9, (200, 220, 240, 255))
    c.circle(103, 32, 7, (16, 24, 48, 255))
    c.vline(64, 0, 64, (216, 246, 255, 220))
    return c


def sheet_icon_rand() -> Canvas:
    c = Canvas(128, 64)
    c.vgradient(0, 0, 128, 64, [(0, (20, 28, 54, 255)), (1, (10, 14, 30, 255))])

    def die(x0: int, pips: list[tuple[int, int]]) -> None:
        _rounded(c, x0, 10, x0 + 42, 52, 8, (232, 240, 252, 255))
        for px, py in pips:
            c.circle(x0 + px, 10 + py, 4, (18, 26, 48, 255))

    die(14, [(10, 10), (31, 10), (10, 31), (31, 31)])
    die(72, [(10, 10), (21, 21), (31, 31)])
    return c


def main() -> int:
    jobs = [
        ("data/debug_font.png", sheet_debug_font),
        ("data/gui_buttons.png", sheet_gui_buttons),
        ("data/themes/none.png", sheet_icon_none),
        ("data/themes/auto.png", sheet_icon_auto),
        ("data/themes/rand.png", sheet_icon_rand),
    ]
    for rel, fn in jobs:
        canvas = fn()
        w, h, _, _ = png_info(ROOT / rel)
        assert (canvas.w, canvas.h) == (w, h), f"{rel}: size changed!"
        canvas.save(ROOT / rel)
        print(f"  painted {rel} ({canvas.w}x{canvas.h})")
    print("font/button/icon pass done")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
