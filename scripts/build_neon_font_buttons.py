INK = (232, 244, 252, 255)


def draw_glyph(c: Canvas, ox: int, oy: int, code: int) -> None:
    for (x0, y0), (x1, y1) in GLYPHS.get(code, []):
        if (x0, y0) == (x1, y1):
            c.rect(ox + x0, oy + y0, ox + x0 + 2, oy + y0 + 2, INK)
        else:
            c.line(ox + x0, oy + y0, ox + x1, oy + y1, INK, width=2)


def sheet_debug_font() -> Canvas:
    assert len(GLYPHS) == 95, f"glyph table has {len(GLYPHS)} entries, want 95"
    c = Canvas(256, 256)
    for code in range(256):
        cx, cy = (code % 16) * 16, (code // 16) * 16
        if 32 <= code <= 126:
            draw_glyph(c, cx + 4, cy + 2, code)
    return c


# ----------------------------------------------------------------------------
# gui buttons (3 x 128px toggle states)
# ----------------------------------------------------------------------------

def _rounded(c: Canvas, x0: int, y0: int, x1: int, y1: int, r: int, rgba) -> None:
    c.rect(x0 + r, y0, x1 - r, y1, rgba)
    c.rect(x0, y0 + r, x1, y1 - r, rgba)
    for cx, cy in ((x0 + r, y0 + r), (x1 - r - 1, y0 + r),
                   (x0 + r, y1 - r - 1), (x1 - r - 1, y1 - r - 1)):
        c.circle(cx, cy, r, rgba)


def _button(c: Canvas, ox: int, frame: tuple, plate: tuple, led: tuple, glow: bool) -> None:
    _rounded(c, ox + 8, 8, ox + 120, 120, 18, frame)
    _rounded(c, ox + 16, 16, ox + 112, 112, 12, plate)
    # top sheen
    c.rect(ox + 24, 22, ox + 104, 30, (255, 255, 255, 28))
    # LED with optional halo
    if glow:
        for r, a in ((30, 40), (22, 80), (15, 140)):
            c.circle(ox + 64, 64, r, led[:3] + (a,))
    c.circle(ox + 64, 64, 12, led)
    c.circle(ox + 60, 60, 4, (255, 255, 255, 220))


def sheet_gui_buttons() -> Canvas:
    c = Canvas(384, 128)
    _button(c, 0, (52, 62, 88, 255), (22, 28, 48, 255), (110, 130, 160, 255), False)
    _button(c, 128, (77, 227, 247, 255), (18, 44, 62, 255), (77, 227, 247, 255), True)
    _button(c, 256, (150, 180, 220, 255), (34, 44, 70, 255), (216, 246, 255, 255), True)
    return c


