#!/usr/bin/env python3
"""Neon Relay original country flag sheet (BL-16 2/2).

Redraws every data/countryflags/*.png (128x64) as our own pixel rendering of
the official (public-domain) flag geometry - a compact DSL describes stripes,
crosses, triangles, cantons, discs, stars and crescents; emblems are
simplified to their dominant shape at icon size. No upstream pixel art is
reused: everything is rasterised here with the house antialiasing pass
(2x supersample + LANCZOS). 'default' gets an original neutral badge.
"""
import math
import pathlib

from PIL import Image, ImageDraw

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "countryflags"
SS = 2
W, H = 128, 64


def C(hexs):
	h = hexs.lstrip("#")
	return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) + (255,)


def star_pts(cx, cy, r, n=5, rot=-90):
	pts = []
	for k in range(n * 2):
		rr = r if k % 2 == 0 else r * 0.45
		a = math.radians(rot + k * (360 / (n * 2)))
		pts.append((cx + rr * math.cos(a), cy + rr * math.sin(a)))
	return pts


class Flag:
	def __init__(self):
		self.img = Image.new("RGBA", (W * SS, H * SS), (0, 0, 0, 0))
		self.d = ImageDraw.Draw(self.img)

	def field(self, col):
		self.d.rectangle([0, 0, W * SS, H * SS], fill=C(col))

	def H(self, cols, fracs=None):
		n = len(cols)
		fr = fracs or [1.0 / n] * n
		y = 0.0
		for col, f in zip(cols, fr):
			self.d.rectangle([0, y * H * SS, W * SS, (y + f) * H * SS], fill=C(col))
			y += f

	def V(self, cols, fracs=None):
		n = len(cols)
		fr = fracs or [1.0 / n] * n
		x = 0.0
		for col, f in zip(cols, fr):
			self.d.rectangle([x * W * SS, 0, (x + f) * W * SS, H * SS], fill=C(col))
			x += f

	def vbar(self, frac, col):
		self.d.rectangle([0, 0, frac * W * SS, H * SS], fill=C(col))

	def nordic(self, bg, col, inner=None, ox=0.36):
		self.field(bg)
		cw = 0.14
		self.d.rectangle([0, (0.5 - cw / 2) * H * SS, W * SS, (0.5 + cw / 2) * H * SS], fill=C(col))
		self.d.rectangle([(ox - cw / 2) * W * SS, 0, (ox + cw / 2) * W * SS, H * SS], fill=C(col))
		if inner:
			iw = cw * 0.45
			self.d.rectangle([0, (0.5 - iw / 2) * H * SS, W * SS, (0.5 + iw / 2) * H * SS], fill=C(inner))
			self.d.rectangle([(ox - iw / 2) * W * SS, 0, (ox + iw / 2) * W * SS, H * SS], fill=C(inner))

	def ccross(self, bg, col, inner=None, t=0.18):
		self.field(bg)
		self.d.rectangle([0, (0.5 - t / 2) * H * SS, W * SS, (0.5 + t / 2) * H * SS], fill=C(col))
		self.d.rectangle([(0.5 - t) * W * SS, 0, (0.5 + t) * W * SS, H * SS], fill=C(col))
		if inner:
			iw = t * 0.45
			self.d.rectangle([0, (0.5 - iw / 2) * H * SS, W * SS, (0.5 + iw / 2) * H * SS], fill=C(inner))
			self.d.rectangle([(0.5 - iw) * W * SS, 0, (0.5 + iw) * W * SS, H * SS], fill=C(inner))

	def saltire(self, quarters, col, width=0.16):
		top, bottom, hoist, fly = quarters
		self.d.polygon([(0, 0), (W * SS, 0), (W * SS, H * SS * 0.5), (0, H * SS * 0.5)], fill=C(top))
		self.d.polygon([(0, H * SS * 0.5), (W * SS, H * SS * 0.5), (W * SS, H * SS), (0, H * SS)], fill=C(bottom))
		self.d.polygon([(0, 0), (W * SS * 0.5, H * SS * 0.5), (0, H * SS)], fill=C(hoist))
		self.d.polygon([(W * SS, 0), (W * SS * 0.5, H * SS * 0.5), (W * SS, H * SS)], fill=C(fly))
		t = width * H * SS
		self.d.line([(0, 0), (W * SS, H * SS)], fill=C(col), width=int(t))
		self.d.line([(0, H * SS), (W * SS, 0)], fill=C(col), width=int(t))

	def diag3(self, top, band, bottom, edged=None):
		self.d.polygon([(0, 0), (W * SS, 0), (0, H * SS)], fill=C(top))
		self.d.polygon([(W * SS, 0), (W * SS, H * SS), (0, H * SS)], fill=C(bottom))
		t = 0.28 * H * SS
		if edged:
			self.d.line([(W * SS, 0), (0, H * SS)], fill=C(edged), width=int(t * 1.5))
		self.d.line([(W * SS, 0), (0, H * SS)], fill=C(band), width=int(t))

	def tri(self, col, frac=0.35, side="hoist"):
		if side == "hoist":
			self.d.polygon([(0, 0), (frac * W * SS, H * SS * 0.5), (0, H * SS)], fill=C(col))
		else:
			self.d.polygon([(W * SS, 0), (W * SS - frac * W * SS, H * SS * 0.5), (W * SS, H * SS)], fill=C(col))

	def sidetri(self, col, frac=0.22):
		self.d.polygon([(0, 0), (frac * W * SS, H * SS * 0.5), (0, H * SS)], fill=C(col))
		self.d.polygon([(W * SS, 0), (W * SS - frac * W * SS, H * SS * 0.5), (W * SS, H * SS)], fill=C(col))

	def canton(self, wf, hf, col):
		self.d.rectangle([0, 0, wf * W * SS, hf * H * SS], fill=C(col))

	def disc(self, col, r, u=0.5, v=0.5):
		cx, cy = u * W * SS, v * H * SS
		self.d.ellipse([cx - r * W * SS, cy - r * W * SS, cx + r * W * SS, cy + r * W * SS], fill=C(col))

	def ring(self, col, r, u=0.5, v=0.5, w=0.03):
		cx, cy = u * W * SS, v * H * SS
		self.d.ellipse([cx - r * W * SS, cy - r * W * SS, cx + r * W * SS, cy + r * W * SS],
			outline=C(col), width=int(w * W * SS))

	def star(self, col, u=0.5, v=0.5, r=0.12, n=5):
		self.d.polygon(star_pts(u * W * SS, v * H * SS, r * W * SS, n), fill=C(col))

	def stars_ring(self, col, u, v, r, n, sr=0.035):
		for k in range(n):
			a = math.radians(-90 + k * 360 / n)
			self.d.polygon(star_pts(u * W * SS + r * W * SS * math.cos(a),
				v * H * SS + r * W * SS * math.sin(a), sr * W * SS), fill=C(col))

	def crescent(self, col, u=0.42, v=0.5, r=0.11):
		cx, cy = u * W * SS, v * H * SS
		rr = r * W * SS
		self.d.ellipse([cx - rr, cy - rr, cx + rr, cy + rr], fill=C(col))
		self.d.ellipse([cx - rr * 0.75, cy - rr, cx + rr * 1.15, cy + rr],
			fill=(0, 0, 0, 0))

	def frame(self, col, t=0.08):
		tw = t * H * SS
		self.d.rectangle([0, 0, W * SS, tw], fill=C(col))
		self.d.rectangle([0, H * SS - tw, W * SS, H * SS], fill=C(col))
		self.d.rectangle([0, 0, tw, H * SS], fill=C(col))
		self.d.rectangle([W * SS - tw, 0, W * SS, H * SS], fill=C(col))

	def done(self):
		return self.img.resize((W, H), Image.LANCZOS)


def union(d, box):
	"""Abstract union-jack canton (original simplified rendering)."""
	x0, y0, x1, y1 = box
	d.rectangle([x0, y0, x1, y1], fill=C("012169"))
	t = (y1 - y0) * 0.16
	d.line([(x0, y0), (x1, y1)], fill=C("ffffff"), width=int(t))
	d.line([(x0, y1), (x1, y0)], fill=C("ffffff"), width=int(t))
	d.rectangle([x0, (y0 + y1) / 2 - t, x1, (y0 + y1) / 2 + t], fill=C("ffffff"))
	d.rectangle([(x0 + x1) / 2 - t, y0, (x0 + x1) / 2 + t, y1], fill=C("ffffff"))
	t2 = t * 0.5
	d.line([(x0, y0), (x1, y1)], fill=C("c8102e"), width=int(t2))
	d.line([(x0, y1), (x1, y0)], fill=C("c8102e"), width=int(t2))
	d.rectangle([x0, (y0 + y1) / 2 - t2, x1, (y0 + y1) / 2 + t2], fill=C("c8102e"))
	d.rectangle([(x0 + x1) / 2 - t2, y0, (x0 + x1) / 2 + t2, y1], fill=C("c8102e"))


def ensign(f, field_col, badge=None):
	f.field(field_col)
	union(f.d, (0, 0, W * SS * 0.42, H * SS * 0.5))
	if badge:
		badge(f)


T = {}


def flag(code):
	def deco(fn):
		T[code] = fn
		return fn
	return deco


