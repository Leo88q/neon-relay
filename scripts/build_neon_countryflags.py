def main():
	OUT.mkdir(parents=True, exist_ok=True)
	written = 0
	for path in sorted(OUT.glob("*.png")):
		code = path.stem
		fn = T.get(code)
		if fn is None:
			continue
		f = Flag()
		fn(f)
		f.done().save(path, "PNG")
		written += 1
	missing = [p.stem for p in OUT.glob("*.png") if p.stem not in T]
	print(f"wrote {written} country flags; missing specs: {missing or 'none'}")
	return 0


